/* ----------------------------- 数据库读取（带缓存） ----------------------------- */

interface ScriptLibraryRow extends RowDataPacket {
  scene_id: string;
  title: string;
  parent_expression: string;
  reply_template: string;
  strategy: string;
  risk: string;
}

/** 内存缓存（避免每次生成话术都查库）。 */
let cache: { scenarios: ScriptScenario[]; ts: number } | null = null;
/** 缓存有效期 5 分钟。 */
const CACHE_TTL = 5 * 60 * 1000;

/**
 * 从数据库 script_library 表读取话术场景。
 *
 * - 带内存缓存（5 分钟），避免每次生成话术都查库
 * - 数据库读取失败或表为空时，回退到硬编码的 SCRIPT_SCENARIOS
 * - 后续在数据库新增场景后，5 分钟内会自动生效
 */
export async function getScriptScenarios(): Promise<ScriptScenario[]> {
  // 命中缓存
  if (cache && Date.now() - cache.ts < CACHE_TTL) {
    return cache.scenarios;
  }

  try {
    const rows = await query<ScriptLibraryRow[]>(
      "SELECT scene_id, title, parent_expression, reply_template, strategy, risk FROM script_library ORDER BY sort_order ASC, id ASC"
    );

    if (rows.length === 0) {
      // 表为空，回退到兜底数据
      return SCRIPT_SCENARIOS;
    }

    const scenarios: ScriptScenario[] = rows.map((r) => ({
      id: r.scene_id,
      title: r.title,
      parentExpression: r.parent_expression,
      replyTemplate: r.reply_template,
      strategy: r.strategy,
      risk: r.risk,
    }));

    cache = { scenarios, ts: Date.now() };
    return scenarios;
  } catch (err) {
    console.error("从数据库读取话术库失败，回退到内置数据:", err);
    return SCRIPT_SCENARIOS;
  }
}

/** 手动清空缓存（管理员更新话术后可调用以立即生效）。 */
export function invalidateScriptCache(): void {
  cache = null;
}
